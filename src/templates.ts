export type TemplateName =
  | "concept"
  | "world-building"
  | "characters"
  | "character-profile"
  | "outline-brief"
  | "outline-detailed"
  | "scenes"
  | "summary"
  | "foreshadow"
  | "character-state"
  | "config"
  | "reality-source"
  | "sect"
  | "martial-art"
  | "weapon"

export function getTemplate(name: TemplateName): string {
  switch (name) {
    case "concept":
      return CONCEPT_TEMPLATE
    case "world-building":
      return WORLD_BUILDING_TEMPLATE
    case "characters":
      return CHARACTER_PROFILES_TEMPLATE
    case "character-profile":
      return CHARACTER_PROFILE_TEMPLATE
    case "outline-brief":
      return OUTLINE_BRIEF_TEMPLATE
    case "outline-detailed":
      return OUTLINE_DETAILED_TEMPLATE
    case "scenes":
      return SCENES_TEMPLATE
    case "summary":
      return SUMMARY_TEMPLATE
    case "reality-source":
      return REALITY_SOURCE_TEMPLATE
    case "sect":
      return WUXIA_SECTS_TEMPLATE
    case "martial-art":
      return WUXIA_MARTIAL_ARTS_TEMPLATE
    case "weapon":
      return WUXIA_WEAPONS_TEMPLATE
    default:
      return ""
  }
}

export function fillTemplateVars(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key) => String(vars[key] ?? `{${key}}`))
}
